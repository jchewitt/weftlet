import { contentDigest } from './files.js';

export function projectMcpLauncher(repositoryId: string, configRelative: string) {
  const key = contentDigest(JSON.stringify([repositoryId, configRelative])).slice(0, 16);
  const path = `.weftlet/mcp-${key}.mjs`;
  const content = `// Generated by Weftlet project setup; refresh through setup --mcp --update.\n` +
    `import { dirname, resolve } from 'node:path';\n` +
    `import { fileURLToPath, pathToFileURL } from 'node:url';\n` +
    `const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');\n` +
    `process.env.CONTEXT_GRAPH_CONFIG = resolve(root, ${JSON.stringify(configRelative)});\n` +
    `process.chdir(root);\n` +
    `try {\n  const entry = fileURLToPath(import.meta.resolve('@weftlet/toolkit'));\n` +
    `  await import(pathToFileURL(resolve(dirname(entry), 'mcp.js')).href);\n` +
    `} catch {\n  process.stderr.write('Weftlet MCP startup failed. Install @weftlet/toolkit in this project and run weftlet config validate.\\n');\n  process.exitCode = 1;\n}\n`;
  // Node receives this as one argument, never through a shell. Search only ancestors of the client cwd.
  const bootstrap = `const fs=require('node:fs'),p=require('node:path'),u=require('node:url');` +
    `let d=process.cwd();for(;;){const f=p.join(d,${JSON.stringify(path)});` +
    `if(fs.existsSync(f)){import(u.pathToFileURL(f).href).catch(()=>{process.stderr.write('Weftlet launcher failed\\n');process.exitCode=1});break;}` +
    `const parent=p.dirname(d);if(parent===d){process.stderr.write('Open this client inside the Weftlet project, or rerun setup with --absolute-launcher.\\n');process.exitCode=1;break;}d=parent;}`;
  return { path, content, bootstrap };
}
