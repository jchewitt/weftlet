import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parse } from 'yaml';

const execute = promisify(execFile);
/** Run generated no-model steps against the real installed toolkit, with hoisted dependencies. */
export async function smokeCiSetup(consumer, installedRoot, initialize = true) {
  const packageDirectory = join(consumer, 'tools', 'ci project');
  const temporary = join(consumer, 'ci-runner-temp');
  await mkdir(packageDirectory, { recursive: true }); await mkdir(temporary);
  await writeFile(join(packageDirectory, 'package.json'), JSON.stringify({ private: true, name: 'ci-public-package',
    devDependencies: { '@weftlet/toolkit': JSON.parse(await readFile(join(installedRoot, 'package.json'), 'utf8')).version },
    scripts: { test: 'node --check fixture.mjs', build: 'node --check fixture.mjs' } }));
  await writeFile(join(packageDirectory, 'fixture.mjs'), 'export const publicValue = 1;\n');
  if (initialize) {
    await writeFile(join(consumer, '.gitignore'), '.context-graph/\nnode_modules/\n');
    await writeFile(join(consumer, 'src/ci-example.ts'), 'export const greeting = "public";\n');
    await writeFile(join(consumer, 'intent.md'), '# Public intent\nReturn a greeting.\n');
    const configPath = join(consumer, 'context-graph.config.json');
    const config = JSON.parse(await readFile(configPath, 'utf8'));
    config.semanticSources = ['intent.md'];
    await writeFile(configPath, JSON.stringify(config));
    await execute('git', ['init', '--quiet'], { cwd: consumer });
    await execute('git', ['add', '--', '.gitignore', 'package.json', 'package-lock.json', 'context-graph.config.json',
      'src/ci-example.ts', 'intent.md', 'tools/ci project/package.json', 'tools/ci project/fixture.mjs'], { cwd: consumer });
    await execute('git', ['-c', 'user.name=Public CI Smoke', '-c', 'user.email=smoke@example.invalid', '-c', 'commit.gpgsign=false',
      'commit', '--quiet', '-m', 'Create committed CI example'], { cwd: consumer });
  }
  await mkdir(join(consumer, '.github/workflows'), { recursive: true });
  const existing = 'name: existing consumer checks\non: push\npermissions: write-all\njobs: {}\n';
  await writeFile(join(consumer, '.github/workflows/existing.yml'), existing);
  const args = ['setup', 'ci', '--checks', '--config', initialize ? 'context-graph.config.json' : 'preview.config.json', '--working-directory', 'tools/ci project',
    '--build-script', 'build', '--test-script', 'test', '--json'];
  const run = async (...extra) => JSON.parse((await execute(process.execPath, [join(installedRoot, 'dist/cli.js'), ...args, ...extra],
    { cwd: consumer, timeout: 60_000, maxBuffer: 2 * 1024 * 1024 })).stdout);
  const plan = await run();
  if (plan.applied || !plan.ready || (await readdir(join(consumer, '.github/workflows'))).includes('weftlet-check.yml')) throw Error('CI preview must not write workflow files');
  await run('--apply', '--expect-plan', plan.planId);
  const workflow = parse(await readFile(join(consumer, plan.files[0].path), 'utf8'));
  if (workflow.on.pull_request === undefined || workflow.permissions.contents !== 'read') throw Error('Incorrect generated check workflow');
  const env = { ...process.env, ...workflow.env, GITHUB_WORKSPACE: consumer, RUNNER_TEMP: temporary,
    GITHUB_SHA: (await execute('git', ['rev-parse', 'HEAD'], { cwd: consumer })).stdout.trim() };
  for (const step of workflow.jobs.checks.steps.filter(step => step.run && step.name !== 'Frozen dependency installation')) {
    // These commands are generated by the reviewed scaffolder, not read from consumer source/workflows.
    await execute('bash', ['--noprofile', '--norc', '-e', '-o', 'pipefail', '-c', step.run],
      { cwd: packageDirectory, env, timeout: 60_000, maxBuffer: 2 * 1024 * 1024 });
  }
  if ((await run()).files[0].action !== 'unchanged' || await readFile(join(consumer, '.github/workflows/existing.yml'), 'utf8') !== existing) {
    throw Error('CI setup must preserve existing workflows and repeat without changes');
  }
  await rm(temporary, { recursive: true, force: true });
}
